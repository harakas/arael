// Files an export no longer writes: a dropped root's, a dropped
// interface's. Only files cargo-arael generated (the stamp on their first
// line) are found and removed, never a write-once scaffold or a file
// without the stamp, and a directory goes only when it is left empty.

use cargo_arael::export::{
    generate_interfaces, leftover_files, refreshed_scaffold, remove_leftovers, Interfaces,
};
use cargo_arael::ir::Model;
use std::path::{Path, PathBuf};

fn files(interfaces: Interfaces) -> Vec<(PathBuf, String)> {
    let m = Model::parse(include_str!("golden/fit.json")).unwrap();
    generate_interfaces(&[&m], "fit-model", "{ version = \"0.9\" }", None, interfaces).unwrap()
}

/// A fresh directory holding a full export of the golden model, plus a
/// stale generated header, a header of the user's, compiled Python and a
/// stamped file in build output.
fn exported(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    for (rel, content) in files(Interfaces::ALL) {
        let path = dir.join(&rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, content).unwrap();
    }
    let put = |rel: &str, content: &[u8]| {
        let path = dir.join(rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, content).unwrap();
    };
    put("cxx/include/dropped.hpp", b"// GENERATED by cargo-arael from the Dropped model sidecar.\n");
    put("cxx/include/mine.hpp", b"// my own helper, not generated\n");
    let pkg = python_package(&files(Interfaces::ALL));
    put(&format!("{pkg}/__pycache__/fit.cpython-312.pyc"), &[0x6f, 0x0d, 0x0d, 0x0a, 0, 0, 0, 0]);
    put("wasm/target/note.txt", b"# GENERATED by cargo-arael: in build output, never searched\n");
    dir
}

/// The generated Python package directory (`python/<namespace>`).
fn python_package(files: &[(PathBuf, String)]) -> String {
    let init = files.iter().find(|(p, _)| p.starts_with("python") && p.ends_with("__init__.py")).unwrap();
    init.0.parent().unwrap().display().to_string()
}

#[test]
fn a_dropped_roots_file_is_a_leftover_and_nothing_else() {
    let dir = exported("leftovers_dropped_root");
    assert_eq!(leftover_files(&dir, &files(Interfaces::ALL)), [PathBuf::from("cxx/include/dropped.hpp")]);
}

#[test]
fn a_dropped_interface_loses_its_generated_files_only() {
    let dir = exported("leftovers_dropped_interface");
    let cxx = files(Interfaces::parse(["cxx"]).unwrap());
    let all = files(Interfaces::ALL);
    let left = leftover_files(&dir, &cxx);

    // Every generated python and wasm file but the wasm scaffold, and the
    // stale header; nothing the export still writes.
    let mut want: Vec<PathBuf> = all.iter().map(|(p, _)| p.clone())
        .filter(|p| (p.starts_with("python") || p.starts_with("wasm"))
            && p != Path::new("wasm/Cargo.toml"))
        .collect();
    want.push(PathBuf::from("cxx/include/dropped.hpp"));
    want.sort();
    assert_eq!(left, want);

    let removed = remove_leftovers(&dir, &left).unwrap();
    for p in &left {
        assert!(!dir.join(p).exists(), "{} still there", p.display());
    }
    // Not generated, a scaffold, build output: all still there.
    let pkg = python_package(&all);
    for kept in ["cxx/include/mine.hpp", "wasm/Cargo.toml", "wasm/target/note.txt",
                 &format!("{pkg}/__pycache__/fit.cpython-312.pyc")] {
        assert!(dir.join(kept).is_file(), "{kept} was removed");
    }
    // A directory goes only when empty: the package keeps its compiled
    // Python, so it and python/ stay; wasm's sources and js are gone,
    // wasm/ keeps its scaffold.
    assert!(dir.join(&pkg).is_dir());
    assert!(!dir.join("wasm/src").exists() && !dir.join("wasm/js").exists());
    assert!(removed.contains(&PathBuf::from("wasm/src")), "{removed:?}");
    assert!(!removed.iter().any(|d| d == Path::new("python") || d == Path::new("wasm")), "{removed:?}");
    // The export's own files are untouched.
    for (p, content) in &cxx {
        assert_eq!(&std::fs::read_to_string(dir.join(p)).unwrap(), content, "{}", p.display());
    }
}

#[test]
fn a_scaffold_header_line_is_refreshed_and_the_rest_kept() {
    let new = &files(Interfaces::ALL).into_iter().find(|(p, _)| p == Path::new("capi/Cargo.toml")).unwrap().1;
    assert!(new.starts_with("# GENERATED by cargo-arael: shim crate for the `fit-model` model."), "{new}");
    let old = "# GENERATED by cargo-arael: shim crate for the `Dropped` / `Fit` model. Written once -- edit freely; delete the file to regenerate.\n[package]\nname = \"fit-model-capi\"\n# my edit\n";
    let updated = refreshed_scaffold(old, new).unwrap();
    assert_eq!(updated.lines().next(), new.lines().next());
    assert!(updated.ends_with("[package]\nname = \"fit-model-capi\"\n# my edit\n"), "{updated}");
    // Current, or a first line the user rewrote: left alone.
    assert_eq!(refreshed_scaffold(&updated, new), None);
    assert_eq!(refreshed_scaffold("# my capi crate\n[package]\n", new), None);
}
