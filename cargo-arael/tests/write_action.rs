// The per-file overwrite policy of `cargo arael export`: generated
// files rewrite their own marker-stamped output and refuse foreign
// files; the capi/Cargo.toml scaffold is written once -- a user's
// edited copy is kept (only the pre-harvest stub is replaced); a file
// that already holds the new content is left untouched.

use cargo_arael::export::{write_action, WriteAction};
use std::path::Path;

const SCAFFOLD: &str = "capi/Cargo.toml";
const GENERATED: &str = "capi/src/lib.rs";
const NEW: &str = "// GENERATED by cargo-arael: do not edit.\npub fn g() {}\n";

#[test]
fn missing_files_are_written() {
    assert_eq!(write_action(Path::new(SCAFFOLD), None, NEW), WriteAction::Write);
    assert_eq!(write_action(Path::new(GENERATED), None, NEW), WriteAction::Write);
}

#[test]
fn stub_scaffold_is_replaced() {
    let stub = "# GENERATED by cargo-arael: placeholder until the export completes. Do not edit.\n[package]\n";
    assert_eq!(write_action(Path::new(SCAFFOLD), Some(stub), NEW), WriteAction::Write);
}

#[test]
fn edited_scaffold_is_kept() {
    // Marker still present (user edited the generated file in place).
    let edited = "# GENERATED by cargo-arael: shim crate. Written once.\n[dependencies]\nserde = \"1\"\n";
    assert_eq!(write_action(Path::new(SCAFFOLD), Some(edited), NEW), WriteAction::Keep);
    // Marker removed entirely.
    assert_eq!(write_action(Path::new(SCAFFOLD), Some("[package]\nname = \"mine\"\n"), NEW),
        WriteAction::Keep);
}

#[test]
fn generated_files_overwrite_their_own_output_only() {
    let marked = "// GENERATED by cargo-arael: do not edit.\npub fn f() {}\n";
    assert_eq!(write_action(Path::new(GENERATED), Some(marked), NEW), WriteAction::Write);
    assert_eq!(write_action(Path::new(GENERATED), Some("hand-written"), NEW), WriteAction::Refuse);
}

#[test]
fn unchanged_generated_files_are_left_alone() {
    assert_eq!(write_action(Path::new(GENERATED), Some(NEW), NEW), WriteAction::Unchanged);
    // The scaffold is kept on its own rule, unchanged or not.
    assert_eq!(write_action(Path::new(SCAFFOLD), Some(NEW), NEW), WriteAction::Keep);
    // One byte of difference is a write.
    let edited = NEW.replace("g()", "h()");
    assert_eq!(write_action(Path::new(GENERATED), Some(&edited), NEW), WriteAction::Write);
}
